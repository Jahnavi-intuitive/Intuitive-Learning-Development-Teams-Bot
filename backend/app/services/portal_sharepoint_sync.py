"""Live SharePoint ingestion for the L&D Portal (lnd_portal database) —
replaces the one-shot local-disk scripts/ingest_real_excel_data.py as the
real source of truth. Reads the same 4 real workbooks
(Anthropic/Gemini/AWS/Databricks) directly from the "REAL EXCEL SHEETS"
subfolder of the "Certification Trackers" SharePoint library via Microsoft
Graph (same app-only credentials already configured for
services/sharepoint_client.py — Sites.Selected, scoped to this one site),
instead of requiring someone to hand-copy files to local disk.

Real-time strategy, confirmed with the user rather than guessed: webhook
change notifications need a public HTTPS endpoint this backend doesn't have
yet (it's local-only right now) — deferred until deployment. For now this
runs on a short scheduled interval (app/services/scheduler.py) as a delta-
style reconciliation: every run re-reads and re-validates each file in
full (not an assumed diff — these files are small, a few hundred rows
total) and upserts by natural key (provider, certification_name,
normalized person name — confirmed with the user; not email, which AWS
never captures and at least one row already has wrong by copy-paste
error). A row that existed for a provider on the last run but is missing
this run is HARD-deleted (confirmed with the user — not soft-deleted).

Never touches any "Summary" sheet/tab a workbook may contain (several of
the *other* provider workbooks in this same library, unrelated to this
folder, are known to have a first-tab Summary sheet regenerated by
services/excel_sync.py's write-back path) — sheet auto-detection below
explicitly skips anything named "Summary", case-insensitive.
"""


import re as _re

_LOOKS_LIKE_DATE = _re.compile(r"^\d{1,2}/\d{1,2}/\d{4}$")


def _is_na(value) -> bool:
    try:
        return bool(pd.isna(value))
    except (TypeError, ValueError):
        return False


def _clean_str(value) -> str | None:
    if _is_na(value):
        return None
    s = str(value).replace("\xa0", " ")
    s = _re.sub(r"\s+", " ", s).strip()
    return s or None


def _normalize_email(value) -> str | None:
    s = _clean_str(value)
    if not s or "@" not in s:
        return None
    return s.lower()


_DATE_FORMATS = ("%d/%m/%Y", "%Y-%m-%d", "%m/%d/%Y")


def _parse_date(value) -> date | None:
    if _is_na(value):
        return None
    if isinstance(value, pd.Timestamp):
        return value.date()
    if isinstance(value, datetime):
        return value.date()
    if isinstance(value, date):
        return value
    s = _clean_str(value)
    if not s:
        return None
    for fmt in _DATE_FORMATS:
        try:
            return datetime.strptime(s, fmt).date()
        except ValueError:
            continue
    return None


def _json_safe(value):
    if _is_na(value):
        return None
    if isinstance(value, (pd.Timestamp, datetime, date)):
        return value.isoformat()
    if isinstance(value, (int, float, str, bool)):
        return value
    return str(value)


def _raw_row_dict(row: pd.Series) -> dict:
    return {str(k): _json_safe(v) for k, v in row.items()}


def _practice_key(raw: str) -> str:
    s = raw.replace("&amp;", "+").replace("&", "+")
    s = _re.sub(r"\s*\+\s*", "+", s)
    s = _re.sub(r"\s+", " ", s).strip().lower()
    return s


def _canonicalize_practice(raw: str | None) -> tuple[str | None, str | None]:
    if not raw:
        return None, None
    if _LOOKS_LIKE_DATE.fullmatch(raw):
        return "Unknown", "practice_field_corrupted_contains_date"
    canonical = _PRACTICE_CANONICAL_MAP.get(_practice_key(raw))
    return (canonical or raw), None


@dataclass
class ParsedRow:
    fields: dict
    source_sheet: str | None
    source_sheet_row: int
    identity: str  # normalized person_name, used as part of the natural key


@dataclass
class RejectedRow:
    source_sheet: str | None
    source_sheet_row: int
    reason: str
    raw_row: dict


@dataclass
class ParseResult:
    rows: list[ParsedRow] = field(default_factory=list)
    rejected: list[RejectedRow] = field(default_factory=list)


# --------------------------------------------------------------------------
# Databricks "Cert Type" canonicalization — DB-backed alias table instead of
# a hardcoded dict, so a brand-new value (a new cert type never seen before)
# gets auto-registered and shows up on the dashboard immediately, rather
# than silently falling through a fixed mapping that needs a code change.
# Bootstrapped with the known typo/abbreviation variants found by directly
# reading the real sheet (see scripts/ingest_real_excel_data.py's original
# DATABRICKS_CERT_NAME_MAP) so those keep resolving correctly on first run.
# --------------------------------------------------------------------------
_DATABRICKS_ALIAS_BOOTSTRAP = {
    "databricks certified data analyst associate": "Databricks Certified Data Analyst Associate",
    "databricks certified machine learning associate": "Databricks Certified Machine Learning Associate",
    "databricks certified generative ai engineer associate": "Databricks Certified Generative AI Engineer Associate",
    "databricks certified data engineer associate": "Databricks Certified Data Engineer Associate",
    "databricks certified data engineer professional": "Databricks Certified Data Engineer Professional",
    "databricks certified data engineer assoociate": "Databricks Certified Data Engineer Associate",
    "databricks associate data engineer": "Databricks Certified Data Engineer Associate",
    "databricks certified machine learning professional": "Databricks Certified Machine Learning Professional",
}


def _resolve_alias(db: Session, provider: Provider, raw_value: str) -> str:
    """Returns the canonical certification name for a raw value as scanned
    from a free-text column (currently only Databricks' "Cert Type").
    Auto-registers a new CertificationAlias row the first time a raw value
    is seen — never requires a code change to recognize a new cert type."""
    raw_key = raw_value.strip().lower()
    existing = db.execute(
        select(CertificationAlias).where(CertificationAlias.provider == provider, CertificationAlias.raw_key == raw_key)
    ).scalar_one_or_none()
    if existing:
        return existing.canonical_name

    canonical = _DATABRICKS_ALIAS_BOOTSTRAP.get(raw_key)
    if canonical is None:
        # Best-effort default: title-case the raw value as scanned. An admin
        # can correct this later (certification_aliases.canonical_name) — see
        # that model's docstring; not yet wired to a UI.
        canonical = raw_value.strip().title()
    db.add(CertificationAlias(provider=provider, raw_key=raw_key, canonical_name=canonical))
    db.flush()
    return canonical


# --------------------------------------------------------------------------
# Per-provider readers — each takes the workbook bytes and returns a
# ParseResult (valid rows + rejected rows, never silently dropped).
# --------------------------------------------------------------------------

def _parse_anthropic(content: bytes, filename: str) -> ParseResult:
    result = ParseResult()
    xl = pd.ExcelFile(io.BytesIO(content))
    sheet = "Detailed-Certification Tracker"
    if sheet not in xl.sheet_names:
        result.rejected.append(RejectedRow(None, 0, f"Expected sheet {sheet!r} not found in {filename}", {}))
        return result
    df = pd.read_excel(xl, sheet_name=sheet)
    for i, row in df.iterrows():
        row_num = i + 1
        raw = _raw_row_dict(row)
        name = _clean_str(row.get("Name"))
        if not name:
            result.rejected.append(RejectedRow(sheet, row_num, "Missing Name", raw))
            continue
        status_raw = _clean_str(row.get("Status"))
        status = _ANTHROPIC_GEMINI_STATUS_MAP.get(status_raw)
        if status is None:
            result.rejected.append(RejectedRow(sheet, row_num, f"Unrecognized Status {status_raw!r}", raw))
            continue
        practice_raw = _clean_str(row.get("Practice"))
        practice_canonical, dq_flag = _canonicalize_practice(practice_raw)
        result.rows.append(ParsedRow(
            fields=dict(
                provider=Provider.anthropic, source_sheet=None,
                certification_name="Claude Architect Certification", certification_level=None,
                person_name=name, person_email=_clean_str(row.get("Email ID")),
                person_email_normalized=_normalize_email(row.get("Email ID")),
                practice_raw=practice_raw, practice_canonical=practice_canonical,
                manager_name=_clean_str(row.get("Manager")), pd_leader_name=_clean_str(row.get("PD/Leader")),
                status_raw=status_raw, status_canonical=status,
                prep_start_date=_parse_date(row.get("Prep Start Date")), exam_date=_parse_date(row.get("Exam Date")),
                submission_date=_parse_date(row.get("Cerification submission Date")), completion_date=None,
                target_date=None, expiry_date=_parse_date(row.get("Expiry Date")),
                certificate_number=_clean_str(row.get("Certificate Number")), comments=_clean_str(row.get("Comments")),
                consent_given=None, total_certs_held=None, certs_at_this_level=None,
                data_quality_flag=dq_flag, source_file=filename, raw_row=raw,
            ),
            source_sheet=sheet, source_sheet_row=row_num, identity=name.strip().lower(),
        ))
    return result


def _parse_gemini(content: bytes, filename: str) -> ParseResult:
    result = ParseResult()
    xl = pd.ExcelFile(io.BytesIO(content))
    # Auto-detect cert sheets rather than a hardcoded list — a newly added
    # sheet (a new Gemini certification track) is picked up automatically on
    # the next sync, no code change needed. "Summary" is never treated as data.
    sheets = [s for s in xl.sheet_names if s.strip().lower() not in _SKIP_SHEET_NAMES]
    for sheet in sheets:
        df = pd.read_excel(xl, sheet_name=sheet)
        if "Name" not in df.columns or "Status" not in df.columns:
            continue  # not a cert-data sheet (e.g. some other non-tracker tab) — skip quietly, not an error
        for i, row in df.iterrows():
            row_num = i + 1
            raw = _raw_row_dict(row)
            name = _clean_str(row.get("Name"))
            status_raw = _clean_str(row.get("Status"))
            if not name or status_raw != "Certified":
                continue  # blank/non-certified rows aren't a validation failure, just not a completion yet
            practice_raw = _clean_str(row.get("Practice"))
            practice_canonical, dq_flag = _canonicalize_practice(practice_raw)
            result.rows.append(ParsedRow(
                fields=dict(
                    provider=Provider.gemini, source_sheet=sheet, certification_name=sheet, certification_level=None,
                    person_name=name, person_email=_clean_str(row.get("Email ID")),
                    person_email_normalized=_normalize_email(row.get("Email ID")),
                    practice_raw=practice_raw, practice_canonical=practice_canonical,
                    manager_name=_clean_str(row.get("Manager")), pd_leader_name=_clean_str(row.get("PD/Leader")),
                    status_raw=status_raw, status_canonical=StatusCanonical.completed,
                    prep_start_date=_parse_date(row.get("Prep Start Date")), exam_date=_parse_date(row.get("Exam Date")),
                    submission_date=_parse_date(row.get("Cerification submission Date")), completion_date=None,
                    target_date=None, expiry_date=_parse_date(row.get("Expiry Date")),
                    certificate_number=_clean_str(row.get("Certificate Number")), comments=_clean_str(row.get("Comments")),
                    consent_given=None, total_certs_held=None, certs_at_this_level=None,
                    data_quality_flag=dq_flag, source_file=filename, raw_row=raw,
                ),
                source_sheet=sheet, source_sheet_row=row_num, identity=name.strip().lower(),
            ))
    return result


def _parse_databricks(db: Session, content: bytes, filename: str) -> ParseResult:
    result = ParseResult()
    xl = pd.ExcelFile(io.BytesIO(content))
    sheet = "Certifications"
    if sheet not in xl.sheet_names:
        result.rejected.append(RejectedRow(None, 0, f"Expected sheet {sheet!r} not found in {filename}", {}))
        return result
    df = pd.read_excel(xl, sheet_name=sheet)
    pd_practice_split = _re.compile(r"^(?P<pd>.*?)\s*\((?P<practice>[^)]*)\)\s*$")
    for i, row in df.iterrows():
        row_num = i + 1
        raw = _raw_row_dict(row)
        name = _clean_str(row.get("Name"))
        completed_raw = _clean_str(row.get("Completed"))
        if not name:
            continue  # trailing pivot/totals rows (no Name) — not real data, not an error either
        status = _DATABRICKS_STATUS_MAP.get(completed_raw)
        if status is None:
            continue  # same trailing-block filter as the original ingestion script
        pd_field = _clean_str(row.get("Practice Director"))
        pd_leader_name, practice_raw = None, None
        if pd_field:
            m = pd_practice_split.match(pd_field)
            if m:
                pd_leader_name, practice_raw = m.group("pd").strip() or None, m.group("practice").strip() or None
            else:
                pd_leader_name = pd_field
        practice_canonical, dq_flag = _canonicalize_practice(practice_raw)
        cert_type_raw = _clean_str(row.get("Cert Type"))
        cert_name = _resolve_alias(db, Provider.databricks, cert_type_raw) if cert_type_raw else None
        comments = " | ".join(filter(None, [_clean_str(row.get("Comments")), _clean_str(row.get("Comment"))])) or None
        result.rows.append(ParsedRow(
            fields=dict(
                provider=Provider.databricks, source_sheet=sheet, certification_name=cert_name, certification_level=None,
                person_name=name, person_email=_clean_str(row.get("Email ID")),
                person_email_normalized=_normalize_email(row.get("Email ID")),
                practice_raw=practice_raw, practice_canonical=practice_canonical,
                manager_name=_clean_str(row.get("Reports To")), pd_leader_name=pd_leader_name,
                status_raw=completed_raw, status_canonical=status,
                prep_start_date=None, exam_date=None, submission_date=None,
                completion_date=_parse_date(row.get("Completion Date")), target_date=_parse_date(row.get("Target Date")),
                expiry_date=None, certificate_number=None, comments=comments,
                consent_given=None, total_certs_held=None, certs_at_this_level=None,
                data_quality_flag=dq_flag, source_file=filename, raw_row=raw,
            ),
            source_sheet=sheet, source_sheet_row=row_num, identity=name.strip().lower(),
        ))
    return result


def _parse_aws(content: bytes, filename: str) -> ParseResult:
    result = ParseResult()
    xl = pd.ExcelFile(io.BytesIO(content))
    sheet = "Certification Register"
    if sheet not in xl.sheet_names:
        result.rejected.append(RejectedRow(None, 0, f"Expected sheet {sheet!r} not found in {filename}", {}))
        return result
    df = pd.read_excel(xl, sheet_name=sheet, skiprows=3)
    for i, row in df.iterrows():
        row_num = i + 1
        raw = _raw_row_dict(row)
        name = _clean_str(row.get("Person"))
        if not name:
            continue
        cert_name = _clean_str(row.get("Certification Name"))
        if not cert_name:
            result.rejected.append(RejectedRow(sheet, row_num, "Missing Certification Name", raw))
            continue
        consent_raw = _clean_str(row.get("Skill Builder Consent"))
        total_held = row.get("Total Certifications Held")
        certs_at_level = row.get("Certifications at This Level")
        result.rows.append(ParsedRow(
            fields=dict(
                provider=Provider.aws, source_sheet=sheet, certification_name=cert_name,
                certification_level=_clean_str(row.get("Certification Level")),
                person_name=name, person_email=None, person_email_normalized=None,
                practice_raw=None, practice_canonical=None, manager_name=None, pd_leader_name=None,
                status_raw=None, status_canonical=StatusCanonical.completed,
                prep_start_date=None, exam_date=None, submission_date=None, completion_date=None,
                target_date=None, expiry_date=None, certificate_number=None, comments=None,
                consent_given=_AWS_CONSENT_MAP.get(consent_raw),
                total_certs_held=int(total_held) if pd.notna(total_held) else None,
                certs_at_this_level=int(certs_at_level) if pd.notna(certs_at_level) else None,
                data_quality_flag=None, source_file=filename, raw_row=raw,
            ),
            source_sheet=sheet, source_sheet_row=row_num, identity=name.strip().lower(),
        ))
    return result


@dataclass
class SyncRunSummary:
    providers_synced: list[str] = field(default_factory=list)
    rows_inserted: int = 0
    rows_updated: int = 0
    rows_deleted: int = 0
    rows_rejected: int = 0
    error: str | None = None


def run_sync(trigger: str = "scheduled", providers: list[Provider] | None = None) -> SyncRunSummary:
    """The one entry point — called by the scheduled job
    (app/services/scheduler.py) and by the admin on-demand trigger
    (POST /api/admin/portal/sync-now). Every run re-reads and re-validates
    each targeted provider's file in full and upserts by natural key
    (provider, certification_name, normalized person name); a row that
    existed last run but is missing this run is hard-deleted."""
    targets = providers or list(_PROVIDER_FILES.keys())
    summary = SyncRunSummary()
    db = PortalSessionLocal()
    log_row = IngestionLog(trigger=trigger, providers_synced=[p.value for p in targets])
    db.add(log_row)
    db.flush()

    try:
        for provider in targets:
            filename = _PROVIDER_FILES[provider]
            try:
                content = sharepoint_client.download_file_in_folder(_FOLDER, filename)
            except sharepoint_client.SharePointError as exc:
                logger.error("Sync: could not download %s: %s", filename, exc)
                summary.error = f"{filename}: {exc}"
                continue
            if content is None:
                logger.warning("Sync: %s not found in %r — skipping this run.", filename, _FOLDER)
                continue

            if provider is Provider.anthropic:
                parsed = _parse_anthropic(content, filename)
            elif provider is Provider.gemini:
                parsed = _parse_gemini(content, filename)
            elif provider is Provider.databricks:
                parsed = _parse_databricks(db, content, filename)
            elif provider is Provider.aws:
                parsed = _parse_aws(content, filename)
            else:
                continue

            for rej in parsed.rejected:
                db.add(IngestionError(
                    provider=provider, source_file=filename, source_sheet=rej.source_sheet,
                    source_row=rej.source_sheet_row, reason=rej.reason, raw_row=rej.raw_row, sync_run_id=log_row.id,
                ))
            summary.rows_rejected += len(parsed.rejected)

            # Natural key confirmed with the user: provider + certification +
            # normalized person name — status is NOT part of it, so a real
            # status change (e.g. in-progress -> completed) updates the same
            # row in place rather than deleting and re-inserting it.
            by_key: dict[tuple, ParsedRow] = {}
            for r in parsed.rows:
                key = (r.fields["certification_name"], r.identity)
                by_key[key] = r  # last one wins if the sheet itself has an exact duplicate row

            existing = {
                (rec.certification_name, rec.person_name.strip().lower() if rec.person_name else None): rec
                for rec in db.execute(select(CertificationRecord).where(CertificationRecord.provider == provider)).scalars()
            }
            seen_keys = set()
            now = datetime.now(timezone.utc)
            for rec_key, r in by_key.items():
                seen_keys.add(rec_key)
                existing_rec = existing.get(rec_key)
                if existing_rec:
                    for k, v in r.fields.items():
                        setattr(existing_rec, k, v)
                    existing_rec.source_sheet_row = r.source_sheet_row
                    existing_rec.last_synced_at = now
                    summary.rows_updated += 1
                else:
                    db.add(CertificationRecord(**r.fields, source_sheet_row=r.source_sheet_row, last_synced_at=now))
                    summary.rows_inserted += 1

            for rec_key, rec in existing.items():
                if rec_key not in seen_keys:
                    db.delete(rec)
                    summary.rows_deleted += 1

            summary.providers_synced.append(provider.value)
            db.flush()

        log_row.rows_inserted = summary.rows_inserted
        log_row.rows_updated = summary.rows_updated
        log_row.rows_deleted = summary.rows_deleted
        log_row.rows_rejected = summary.rows_rejected
        log_row.error = summary.error
        log_row.finished_at = datetime.now(timezone.utc)
        db.commit()
    except Exception as exc:  # noqa: BLE001 — a sync run must never crash the scheduler; log and surface via IngestionLog
        db.rollback()
        logger.exception("Portal SharePoint sync run failed")
        db2 = PortalSessionLocal()
        try:
            failed_log = IngestionLog(
                trigger=trigger, providers_synced=[p.value for p in targets],
                error=str(exc), finished_at=datetime.now(timezone.utc),
            )
            db2.add(failed_log)
            db2.commit()
        finally:
            db2.close()
        summary.error = str(exc)
    finally:
        db.close()

    return summary
